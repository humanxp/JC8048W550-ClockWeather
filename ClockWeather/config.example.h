/* ---------------------------------------------------------------------------
 *  1. WiFi
 *  改成你自己家的 WiFi。注意：ESP32 只支持 2.4GHz，不支持 5GHz 频段。
 * ------------------------------------------------------------------------ */
#define WIFI_SSID           "你的WiFi名称"
#define WIFI_PASSWORD       "你的WiFi密码"

/* 连接超时（毫秒）。超时后会先进入界面，并在后台自动重连。 */
#define WIFI_CONNECT_TIMEOUT_MS   20000


/* ---------------------------------------------------------------------------
 *  2. 位置（决定天气和时区）
 *
 *  方式一（推荐）：填经纬度，最准确。
 *      查法：https://www.latlong.net/ 搜你的城市，或高德/百度地图右键「复制坐标」。
 *
 *  方式二（懒人）：把 CITY_LAT 和 CITY_LON 都改成 0，程序会自动用 CITY_NAME
 *      去 Open-Meteo 的地理编码接口查一次坐标，结果存进 Flash，以后不再查询。
 *      这时 CITY_NAME 也就是界面左上角显示的城市名。
 *
 *  ⚠ 最常见的编译错误：想把经纬度改成 0，结果写成了 "0f"。
 *     C/C++ 里 0f 不是合法的小数（会被当成「整数 0 + 后缀 f」而报
 *     unable to find numeric literal operator 'operator""f'）。
 *     写 0 或 0.0 都对，就是别写 0f。
 * ------------------------------------------------------------------------ */
#define CITY_NAME           "宁波"
#define CITY_LAT            29.87819      /* 纬度，北纬为正；改成 0 表示自动查坐标 */
#define CITY_LON            121.54945     /* 经度，东经为正；改成 0 表示自动查坐标 */


/* ---------------------------------------------------------------------------
 *  3. 时区与 NTP 授时
 *
 *  TIMEZONE 是 POSIX 时区串，中国是 "CST-8"（注意负号表示东八区，不是写错）。
 *  其他常用值：
 *      "CST-8"                 中国
 *      "HKT-8"                 香港
 *      "JST-9"                 日本
 *      "KST-9"                 韩国
 *      "SGT-8"                 新加坡
 *      "UTC0"                  协调世界时
 *      "GMT0BST,M3.5.0/1,M10.5.0"   英国（含夏令时）
 *      "EST5EDT,M3.2.0,M11.1.0"     美国东部（含夏令时）
 * ------------------------------------------------------------------------ */
#define TIMEZONE            "CST-8"
#define NTP_SERVER_1        "ntp.aliyun.com"
#define NTP_SERVER_2        "cn.pool.ntp.org"
#define NTP_SERVER_3        "pool.ntp.org"


/* ---------------------------------------------------------------------------
 *  4. 刷新策略
 * ------------------------------------------------------------------------ */
#define WEATHER_REFRESH_MIN     15      /* 天气刷新间隔（分钟），Open-Meteo 建议 >= 15 */
#define CLOCK_TICK_MS           200     /* 时钟刷新间隔（毫秒） */
#define USE_24H_FORMAT          1       /* 1 = 24 小时制，0 = 12 小时制（上/下午） */


