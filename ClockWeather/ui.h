#pragma once

#include <lvgl.h>
#include <time.h>

#include "weather.h"

/** 顶栏网络状态（决定文字颜色） */
enum UiStatus {
    UI_STATUS_OFFLINE = 0,   /* 未联网（红） */
    UI_STATUS_CONNECTING,    /* 连接中/同步中（琥珀） */
    UI_STATUS_ONLINE,        /* 已联网（绿） */
    UI_STATUS_ERROR          /* 出错（红） */
};

/** 创建全部界面控件。 */
void ui_init();

/** 时间变化时调用，刷新时钟与日期。 */
void ui_update_time(const struct tm *t);

/** 天气拉取成功后调用。 */
void ui_update_weather(const WeatherData *w);

/** 更新顶栏状态文字与颜色。 */
void ui_set_status(UiStatus st, const char *text);

/** 更新顶栏右上角「更新 xx:xx」。 */
void ui_set_updated(const char *hhmm);

/** 更新左上角城市名（地理编码成功后调用）。 */
void ui_set_city(const char *city);
