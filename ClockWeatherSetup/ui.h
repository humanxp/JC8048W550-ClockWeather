#pragma once

#include <lvgl.h>
#include <time.h>

#include "weather.h"

/** 顶栏网络状态（决定文字颜色） */
enum UiStatus {
    UI_STATUS_OFFLINE = 0,   /* 未联网（红） */
    UI_STATUS_CONNECTING,    /* 连接中/同步中（琥珀） */
    UI_STATUS_ONLINE,        /* 已联网（绿） */
    UI_STATUS_ERROR          /* 出错（红） */
};

/** 创建全部界面控件（两张主屏 + 设置向导）。 */
void ui_init();

/* ------------------------------ 主屏切换 ------------------------------ */

/** 切到满屏大时钟。 */
void ui_show_idle();

/** 切到时间 + 天气看板，并重置「自动回大时钟」计时。 */
void ui_show_dashboard();

/** 当前是否停在看板屏上。 */
bool ui_is_dashboard();

/** 主循环里调用：看板停留超时后自动回大时钟（见 config.h 的 IDLE_RETURN_MIN）。 */
void ui_poll();

/* ------------------------------ 数据刷新 ------------------------------ */

/** 时间变化时调用，刷新两张屏的时钟与日期。 */
void ui_update_time(const struct tm *t);

/** 天气拉取成功后调用（只作用于看板屏）。 */
void ui_update_weather(const WeatherData *w);

/** 更新顶栏状态文字与颜色（大时钟屏上只更新那个小圆点）。 */
void ui_set_status(UiStatus st, const char *text);

/** 更新顶栏右上角「更新 xx:xx」。 */
void ui_set_updated(const char *hhmm);

/** 更新看板左上角城市名。 */
void ui_set_city(const char *city);

/** 大时钟页「刷新天气」按钮被点了：主循环用这个取请求（取完自动清掉）。 */
bool ui_take_weather_refresh_request();

/** 天气刷新开始 / 结束时调用，切换按钮文字（刷新天气 / 刷新中…）。 */
void ui_set_weather_refreshing(bool refreshing);

/**
 * 打印一行 LVGL 内存池用量到串口（DEBUG_SERIAL=1 时有效）。
 * 界面出现「卡死 / 花屏 / 控件不见了」时，先看这个数字：
 * 已用接近总量就说明 LV_MEM_SIZE 太小。
 */
void ui_log_mem(const char *tag);
