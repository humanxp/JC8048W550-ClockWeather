/**
 * ============================================================================
 *  config.h  —  出厂默认配置（ClockWeatherSetup / 带设置向导的版本）
 *
 *  和 ClockWeather 的区别：
 *      这里的 WiFi 和城市只是「出厂默认值」，全部可以留空。
 *      留空的话，第一次开机屏幕会直接进设置向导：
 *          ① 扫描附近的 WiFi，点一下选中，输密码连接
 *          ② 选省份 / 城市（决定天气坐标）
 *      配置结果存进 ESP32 的 Flash（NVS），以后开机会自动用，不用再改代码。
 *
 *      当然也可以像以前那样在这里写死（写了就跳过对应步骤），
 *      适合一次性烧给别人的成品。
 *
 *  开发板：JC8048W550 / ESP32-S3-WROOM-1 N16R8 + 5 寸 800x480 IPS 电容屏
 * ============================================================================
 */
#pragma once

/* ---------------------------------------------------------------------------
 *  1. WiFi（可留空 —— 留空则由屏幕上的设置向导填写）
 *  注意：ESP32 只支持 2.4GHz，不支持 5GHz 频段。
 * ------------------------------------------------------------------------ */
#define WIFI_SSID           ""
#define WIFI_PASSWORD       ""


/* ---------------------------------------------------------------------------
 *  2. 地区（可留空 —— 留空则由屏幕上的设置向导选择）
 *  向导会在全国 34 个省级行政区 / 389 个城市里选，坐标自动带出来。
 *  想在这里写死也可以：填城市名 + 经纬度（都是 0 表示交给向导）。
 * ------------------------------------------------------------------------ */
#define CITY_NAME           ""            /* 界面左上角显示的名字 */
#define CITY_LAT            0.0f         /* 纬度，北纬为正 */
#define CITY_LON            0.0f         /* 经度，东经为正 */


/* ---------------------------------------------------------------------------
 *  3. 时区与 NTP 授时
 *  地区向导目前覆盖中国全境，所以时区固定东八区。
 *  TIMEZONE 是 POSIX 时区串，"CST-8" 的负号表示「本地时间 = UTC + 8」，不是写错。
 * ------------------------------------------------------------------------ */
#define TIMEZONE            "CST-8"
#define NTP_SERVER_1        "ntp.aliyun.com"
#define NTP_SERVER_2        "cn.pool.ntp.org"
#define NTP_SERVER_3        "pool.ntp.org"


/* ---------------------------------------------------------------------------
 *  3.5 天气接口
 *
 *  默认用 Open-Meteo（免 API Key、免费）。如果串口一直报
 *  「天气接口连不上（connection refused）」，多半是这个域名在你那边
 *  解析或连接不通 —— 常见于部分网络环境。
 *
 *  可以换成任何返回格式和 Open-Meteo 一致的地址（比如自己搭的反代，
 *  或者别的镜像）。换域名不影响解析代码。
 * ------------------------------------------------------------------------ */
#define WEATHER_HOST        "api.open-meteo.com"

/* 天气接口要不要用 TLS：
 *   0 = 直接走明文 HTTP（默认）。不走 mbedTLS，只要几 KB 内存，
 *       国内网络对 80 端口也更宽松。天气数据不敏感，够用。
 *   1 = 先试 HTTPS，连续内存不够或失败时自动改明文 HTTP。
 * 实测这台机器跑起来后「最大连续堆」只有 ~25KB（扫描 WiFi 时 8KB），
 * 而 TLS 握手要十几 KB 连续内存 —— 所以默认给 0，别改回 1 除非你确认内存宽裕。
 */
#define WEATHER_TRY_TLS_FIRST   0


/* ---------------------------------------------------------------------------
 *  4. 刷新策略
 * ------------------------------------------------------------------------ */
#define WEATHER_REFRESH_MIN     15      /* 天气刷新间隔（分钟），Open-Meteo 建议 >= 15 */
#define CLOCK_TICK_MS           200     /* 时钟刷新间隔（毫秒） */
#define USE_24H_FORMAT          1       /* 1 = 24 小时制，0 = 12 小时制 */


/* ---------------------------------------------------------------------------
 *  5. 界面 / 交互
 *
 *  IDLE_RETURN_MIN：
 *      平时屏幕上是「满屏大时钟」；点一下屏幕才切到「时间 + 天气」看板。
 *      看板停留这么久没有操作，就自动回到大时钟。默认 5 分钟。
 * ------------------------------------------------------------------------ */
#define IDLE_RETURN_MIN         5
#define UI_TIMEZONE_LABEL       ""      /* 想在城市名后面加后缀可填，例如 " · 中国" */
