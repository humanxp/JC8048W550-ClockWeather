/* 固件版本标记：开机第一行会打印。
 * 换过代码但串口里这行没变 → 说明烧进去的还是旧固件，别怀疑代码。
 * 每次改动都建议把这个号 +1。
 *
 * v2.0 改动（相对 v1.8）：
 *   · 去掉「每 5 秒手动复位 DMA」：IDF 构建里 CONFIG_LCD_RGB_RESTART_IN_VSYNC
 *     已经是开的，驱动每帧自己在 VSYNC 复位，手动那次纯属多余还容易插一条线
 *   · flush 整行宽的块合并成一次 memcpy + 一次 cache 写回（老代码按行走，
 *     480 行就是 480 次写回，白占 CPU 和 PSRAM 总线）
 *   · 串口诊断命令拆到 diag.cpp：help / bench / stats / pclk / bounce / restart
 *   · 串口存档 bounce 行数（NVS），下一次开机生效，方便做对照实验
 *
 * v2.1 改动（bench 实测驱动，推翻了 v1.9「12 行」的猜测）：
 *   · 搬运缓冲 12 行的热拷贝 499µs / 期限 600µs，仍在抖。真原因是
 *     「源 19.2KB + 目的 19.2KB = 38.4KB > 32KB L1」——memcpy 的**目的区**
 *     也要占 cache line，工作集是「2 × 一块字节数」，只算源那一半就会算错
 *   · 余量只能靠「块变小」赚（PCLK 那边看 v2.2）
 *
 * v2.2 改动（实板打回）：
 *   · v2.1 把 PCLK 降到 14.55MHz 是错的：这块 ST7262 **只认 16MHz**，
 *     14.55MHz 会整屏蓝/白/绿/红纯色块乱跳（面板锁不住画面），
 *     `pclk 16` 立刻恢复。已改回 16000000。
 *   · 搬运缓冲定 6 行（源+目的 19.2KB）：余量最宽，8 行只有 +11~37%。
 *
 * v2.3 改动（自己接管搬运缓冲，短线问题量化收尾）：
 *   · display.cpp 不再用 Arduino_GFX 建面板，改成直接 esp_lcd_new_rgb_panel()，
 *     并用 flags.no_fb + on_bounce_empty **自己填搬运缓冲**。原因：IDF 在
 *     num_fbs==0 时不做任何 cache 预读，而它原生只提前 1 块。我们做成运行时可调。
 *     → 顺带不再需要给 Arduino_GFX 打 _panel_handle 补丁，固件也小了 12KB。
 *   · 中断里直接统计每次填充耗时/超期限次数，串口 stats 一眼看出有没有超：
 *     提前 0 块 0.57% → 提前 1 块 0.002%（5.4 万次里 1 次），默认 1 块。
 *   · 新命令：prefetch 0/1/2
 *
 * v2.4 改动（定位到短线真正的成因，按「边界最少」取值）：
 *   · 放大照片后看清：短线是**每块搬运缓冲边界那一行整体左移约 16px**
 *     （16 = LCD FIFO 深度），不是"拷贝太慢"——stats 显示超期限只有 0.01%。
 *     所以块越大边界越少、短线越稀。扫了 8/12/16/20/24 行：
 *         8 行 0.03% / 12 行 0% / 16 行 0% / 20 行 0%（余量仅 5%）/ 24 行 0.05%
 *     取 **16 行**：零超期限 + 边界数只有 6 行的 1/3。
 *   · dma_burst_size 实测只能 64（128/256 被 GDMA 拒绝），现在会自动降档，
 *     不会再因为改这个参数进重启循环。
 */
