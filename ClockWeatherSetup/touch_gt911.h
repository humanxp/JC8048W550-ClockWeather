/**
 * ============================================================================
 *  touch_gt911.h / touch_gt911.cpp  —  GT911 电容触摸驱动
 *
 *  自己用 Wire 实现，不依赖任何第三方触摸库，避免版本不兼容。
 *
 *  GT911 要点：
 *    1. I2C 地址在复位时由 INT 引脚电平决定：INT 低 -> 0x5D，INT 高 -> 0x14。
 *       本板 INT 默认下拉，所以是 0x5D；程序里会把两个地址都探一遍。
 *    2. 寄存器 0x814E 是状态寄存器：bit7 = 有新数据，低 4 位 = 触摸点数。
 *       读完后必须写 0 清标志，否则不会再更新。
 *    3. 连续点击不抬起时，GT911 不一定重复置位 bit7，所以本驱动会缓存
 *       上一次的按下状态（1.5 秒无新数据才判定松开），否则拖动会断。
 * ============================================================================
 */
#pragma once

#include <stdbool.h>
#include <stdint.h>

/** 复位并初始化 GT911。返回 false 表示没找到触摸芯片。 */
bool touch_init();

/**
 * 读取当前触摸状态。
 * 返回 true 表示有手指按下，并把屏幕坐标写进 x / y（已做方向映射）。
 * 返回 false 表示无触摸。
 */
bool touch_read(int32_t *x, int32_t *y);

/** 返回探测到的 I2C 地址（0 表示没找到）。 */
uint8_t touch_addr();

/**
 * 触摸诊断快照（给设置向导顶部的调试行用）。
 *
 * 为什么需要它：ClockWeather 版界面是只读的，触摸只验证过「坐标读得对」，
 * 没验证过「点得动」。设置向导是第一个有可点控件的界面，
 * 万一点了没反应，需要一眼看出是
 *   ① 根本没找到 GT911（多半是 USB CDC 占了 GPIO19/20，或排线没插）
 *   ② 坐标映射不对（左右/上下镜像、XY 交换）
 *   ③ 事件处理的问题
 * 这一行就能区分：地址是 0 -> ①；按次数在涨但坐标不对 -> ②；
 * 坐标对、按次数在涨却还是没反应 -> ③。
 */
struct TouchDiag {
    uint8_t  addr;          /* 0 = 没探测到 GT911 */
    bool     pressed;       /* 当前是否按下 */
    int32_t  x, y;          /* 最近一次映射后的屏幕坐标 */
    uint32_t press_count;   /* 累计按下次数 */
    uint32_t read_fail;     /* I2C 读失败次数 */
    uint16_t raw_max_x;     /* 芯片内部配置的 X 分辨率 */
    uint16_t raw_max_y;     /* 芯片内部配置的 Y 分辨率 */
    bool     swap_xy;       /* 是否交换了 XY */
};

/** 取一份诊断快照（只读，不影响正常读取）。 */
void touch_diag(TouchDiag *out);
